// Every other column may be left out of the file. They are also the fields
// every row needs; a blank product_sku is generated by the server.
const REQUIRED_CSV_HEADERS = [
  'product_name',
  'category',
  'product_image_url',
] as const;

const MAX_UPLOAD_SIZE_BYTES = 10 * 1024 * 1024;

const normalize = (value: string) => value.trim().toLowerCase();

// Handles every Excel CSV format: "CSV UTF-8" (the decoder strips its BOM) and
// the older "CSV (Comma delimited)", which is Windows-1252 rather than UTF-8.
const decodeCsvBuffer = (buffer: ArrayBuffer): string => {
  try {
    return new TextDecoder('utf-8', { fatal: true }).decode(buffer);
  } catch {
    return new TextDecoder('windows-1252').decode(buffer);
  }
};

const detectDelimiter = (headerLine = ''): ',' | ';' =>
  !headerLine.includes(',') && headerLine.includes(';') ? ';' : ',';

const normalizeDecimalComma = (value = '') =>
  /^\d+,\d{1,2}$/.test(value) ? value.replace(',', '.') : value;

const parseCsvLine = (line: string, delimiter: ',' | ';' = ','): string[] => {
  const values: string[] = [];
  let current = '';
  let inQuotes = false;

  for (let i = 0; i < line.length; i += 1) {
    const char = line[i];

    if (char === '"') {
      if (inQuotes && line[i + 1] === '"') {
        current += '"';
        i += 1;
      } else {
        inQuotes = !inQuotes;
      }
      continue;
    }

    if (char === delimiter && !inQuotes) {
      values.push(current);
      current = '';
      continue;
    }

    current += char;
  }

  values.push(current);
  return values.map((value) => value.trim());
};

const isValidHttpUrl = (value: string) => {
  if (!value) return false;
  return /^https?:\/\//i.test(value.trim());
};

const isFiniteNumber = (value: string) => {
  if (!value) return false;
  return Number.isFinite(Number(value));
};

const hasAnyValue = (row: CsvRow, keys: string[]) =>
  keys.some((key) => (row[key] ?? '').trim() !== '');

// Rows of one product share its SKU or, when that is blank, its name
// (ignoring case), like the server groups them.
const productKeyOf = (row: CsvRow) => {
  const sku = (row.product_sku ?? '').trim();
  const name = normalize(row.product_name ?? '');
  return sku || (name ? `name:${name}` : '');
};

const productLabelOf = (row: CsvRow) =>
  (row.product_sku ?? '').trim() || (row.product_name ?? '').trim();

// A blank stock type means unlimited, or limited when a quantity is given.
const stockTypeOf = (type = '', quantity = '') =>
  normalize(type) || (quantity.trim() ? 'limited' : 'unlimited');

// A product with at least one such row is a product with variations;
// without any it is a single product.
const isCompleteVariation = (row: CsvRow) =>
  Boolean(
    (row.variation_name ?? '').trim() && (row.variation_price ?? '').trim(),
  );

// Reads "Regular|Large" as the variation names an add-on group is offered with.
const parseVariationNames = (value = '') =>
  value
    .split('|')
    .map((name) => name.trim())
    .filter(Boolean);

// Reads "Calories: 320 kcal; Protein: 12 g" as [name, detail] pairs.
const parseNamedList = (value = ''): Array<[string, string]> =>
  value
    .split(';')
    .map((entry) => entry.trim())
    .filter(Boolean)
    .map((entry) => {
      const separator = entry.indexOf(':');
      return separator < 0
        ? [entry, '']
        : [entry.slice(0, separator).trim(), entry.slice(separator + 1).trim()];
    });

const nutritionFactsError = (value: string): string | null => {
  const facts = parseNamedList(value);
  if (facts.length > NUTRITION_FACTS_MAX_ENTRIES) {
    return `Use at most ${NUTRITION_FACTS_MAX_ENTRIES} nutrition facts`;
  }
  if (facts.some(([label, detail]) => !label || !detail)) {
    return 'Write each nutrition fact as Name: value, separated by ;';
  }
  if (
    facts.some(
      ([label, detail]) =>
        label.length > NUTRITION_FACT_MAX_LENGTH ||
        detail.length > NUTRITION_FACT_MAX_LENGTH,
    )
  ) {
    return `Nutrition names and values can have at most ${NUTRITION_FACT_MAX_LENGTH} characters`;
  }
  const labels = facts.map(([label]) => label.toLowerCase());
  return new Set(labels).size === labels.length
    ? null
    : 'Each nutrition fact can be listed only once';
};

const allergensError = (value: string): string | null => {
  const allergens = parseNamedList(value).map(
    ([allergen, note]) => [normalize(allergen).replace(/\s+/g, '_'), note] as const,
  );
  const unknown = allergens.find(
    ([allergen]) => !(ALLERGEN_KEYS as readonly string[]).includes(allergen),
  );
  if (unknown) return `"${unknown[0]}" is not a supported allergen`;
  if (allergens.some(([, note]) => note.length > ALLERGEN_NOTE_MAX_LENGTH)) {
    return `Allergen notes can have at most ${ALLERGEN_NOTE_MAX_LENGTH} characters`;
  }
  const names = allergens.map(([allergen]) => allergen);
  return new Set(names).size === names.length
    ? null
    : 'Each allergen can be listed only once';
};

// Optional category schedule, read like the server: 7:00, 07:00, 07:00:00 or
// 7:00 PM become "HH:mm"; null when the value is not a time.
const parseScheduleTime = (value: string): string | null => {
  const match = /^(\d{1,2}):(\d{2})(?::(\d{2}))?\s*([ap]\.?\s?m\.?)?$/i.exec(value.trim());
  if (!match) return null;
  let hours = Number(match[1]);
  const minutes = Number(match[2]);
  const seconds = match[3] === undefined ? 0 : Number(match[3]);
  const meridiem = match[4]?.toLowerCase().replace(/[.\s]/g, '');
  if (minutes > 59 || seconds !== 0) return null;
  if (meridiem) {
    if (hours < 1 || hours > 12) return null;
    hours = (hours % 12) + (meridiem === 'pm' ? 12 : 0);
  } else if (hours > 23) {
    return null;
  }
  return `${String(hours).padStart(2, '0')}:${String(minutes).padStart(2, '0')}`;
};

const categoryScheduleOf = (row: CsvRow) => {
  const from = (row.category_available_from ?? '').trim();
  const until = (row.category_available_until ?? '').trim();
  return { from, until, fromTime: parseScheduleTime(from), untilTime: parseScheduleTime(until) };
};

const categoryScheduleError = (
  row: CsvRow,
): { field: string; message: string } | null => {
  const { from, until, fromTime, untilTime } = categoryScheduleOf(row);
  if (!from && !until) return null;
  if (!from || !until) {
    return {
      field: from ? 'category_available_until' : 'category_available_from',
      message:
        'Fill both category_available_from and category_available_until to schedule a category, or leave both empty',
    };
  }
  if (!fromTime) {
    return {
      field: 'category_available_from',
      message: 'category_available_from must be a time such as 07:00 or 7:00 PM',
    };
  }
  if (!untilTime) {
    return {
      field: 'category_available_until',
      message: 'category_available_until must be a time such as 23:30 or 11:30 PM',
    };
  }
  return fromTime === untilTime
    ? {
        field: 'category_available_until',
        message: 'category_available_from and category_available_until must be different times',
      }
    : null;
};

// Same rules as the add-on form. The limit against the number of options is
// checked after all rows are read.
const selectionLimitsError = (row: CsvRow): string | null => {
  const min = (row.addon_min_select ?? '').trim();
  const max = (row.addon_max_select ?? '').trim();
  if (!min && !max) return null;
  if (normalize(row.addon_selection_type ?? '') !== 'multiple') {
    return 'Leave minimum and maximum empty unless addon_selection_type is multiple';
  }
  if ((min && !/^\d+$/.test(min)) || (max && !/^\d+$/.test(max))) {
    return 'Minimum and maximum must be whole numbers';
  }
  if (Number(min) > 0 && normalize(row.addon_required ?? '') !== 'yes') {
    return 'Minimum must be empty or 0 when addon_required is no';
  }
  if (Number(max) > 0 && Number(min) > Number(max)) {
    return 'Minimum cannot be greater than maximum';
  }
  return null;
};

const buildCsvPreview = (
  rawCsv: string,
  messages: CsvValidationMessages,
): CsvPreviewState => {
  const nonEmptyLines = rawCsv
    .replace(/\r\n/g, '\n')
    .replace(/\r/g, '\n')
    .split('\n')
    .filter((line) => line.trim() !== '');
  const delimiter = detectDelimiter(nonEmptyLines[0]);
  const lines = nonEmptyLines.filter((line) =>
    parseCsvLine(line, delimiter).some(Boolean),
  );

  if (!lines.length) {
    return {
      headers: [],
      rows: [],
      errors: [{ row: 1, field: 'file', message: 'CSV file is empty' }],
    };
  }

  const headers = parseCsvLine(lines[0], delimiter);
  const errors: CsvValidationError[] = [];
  const expectedColumnCount = headers.length;

  headers.forEach((header) => {
    if (!(CSV_HEADERS as readonly string[]).includes(header)) {
      errors.push({
        row: 1,
        field: header,
        message: `Unknown column: ${header}`,
      });
    }
  });

  REQUIRED_CSV_HEADERS.forEach((header) => {
    if (!headers.includes(header)) {
      errors.push({
        row: 1,
        field: header,
        message: `Missing required header: ${header}`,
      });
    }
  });

  const rows = lines.slice(1).map((line) => {
    const values = parseCsvLine(line, delimiter);
    const row: CsvRow = {};
    row.__columnCount = String(values.length);

    headers.forEach((header, index) => {
      row[header] = values[index] ?? '';
    });

    // Excel writes semicolon files in regions that also use a decimal comma.
    if (delimiter === ';') {
      row.variation_price = normalizeDecimalComma(row.variation_price);
      row.product_price = normalizeDecimalComma(row.product_price);
      row.addon_option_price = normalizeDecimalComma(row.addon_option_price);
    }

    return row;
  });

  rows.forEach((row, index) => {
    const rowNumber = index + 2;
    const rowColumnCount = Number(row.__columnCount ?? 0);

    if (rowColumnCount !== expectedColumnCount) {
      errors.push({
        row: rowNumber,
        field: 'CSV Row',
        message: `Column mismatch: expected ${expectedColumnCount}, got ${rowColumnCount}. Check missing/extra comma.`,
      });
      return;
    }

    const looksMisalignedAddon =
      ['yes', 'no'].includes(normalize(row.addon_group_name ?? '')) ||
      ['single', 'multiple'].includes(normalize(row.addon_required ?? '')) ||
      ['limited', 'unlimited'].includes(normalize(row.addon_option_price ?? '')) ||
      isFiniteNumber(row.addon_option_stock_type ?? '');

    if (looksMisalignedAddon) {
      errors.push({
        row: rowNumber,
        field: 'CSV Row',
        message:
          'Row appears misaligned from add-on columns. Check commas before addon_group_name.',
      });
      return;
    }

    REQUIRED_CSV_HEADERS.forEach((field) => {
      if (!(row[field] ?? '').trim()) {
        errors.push({ row: rowNumber, field, message: `${field} is required` });
      }
    });

    const scheduleError = categoryScheduleError(row);
    if (scheduleError) {
      errors.push({ row: rowNumber, ...scheduleError });
    }

    const productPrice = (row.product_price ?? '').trim();
    if (
      productPrice &&
      !(Number.isFinite(Number(productPrice)) && Number(productPrice) > 0)
    ) {
      errors.push({
        row: rowNumber,
        field: 'product_price',
        message: messages.productPriceInvalid(),
      });
    }

    const productNutritionError = nutritionFactsError(
      row.product_nutrition_facts ?? '',
    );
    if (productNutritionError) {
      errors.push({
        row: rowNumber,
        field: 'product_nutrition_facts',
        message: productNutritionError,
      });
    }

    const productAllergenError = allergensError(row.product_allergens ?? '');
    if (productAllergenError) {
      errors.push({
        row: rowNumber,
        field: 'product_allergens',
        message: productAllergenError,
      });
    }

    const productStockType = stockTypeOf(
      row.product_stock_type,
      row.product_stock_quantity,
    );
    if (!['limited', 'unlimited'].includes(productStockType)) {
      errors.push({
        row: rowNumber,
        field: 'product_stock_type',
        message: 'product_stock_type must be limited or unlimited',
      });
    }

    if (productStockType === 'limited') {
      if (!(row.product_stock_quantity ?? '').trim()) {
        errors.push({
          row: rowNumber,
          field: 'product_stock_quantity',
          message: 'product_stock_quantity is required for limited stock',
        });
      } else if (!isFiniteNumber(row.product_stock_quantity)) {
        errors.push({
          row: rowNumber,
          field: 'product_stock_quantity',
          message: 'product_stock_quantity must be a valid number',
        });
      }
    }

    if (productStockType === 'unlimited' && (row.product_stock_quantity ?? '').trim()) {
      errors.push({
        row: rowNumber,
        field: 'product_stock_quantity',
        message: 'product_stock_quantity must be empty for unlimited stock',
      });
    }

    if ((row.product_image_url ?? '').trim() && !isValidHttpUrl(row.product_image_url)) {
      errors.push({
        row: rowNumber,
        field: 'product_image_url',
        message: 'product_image_url must be a valid public URL',
      });
    }

    const variationFields = [
      'variation_name',
      'variation_sku',
      'variation_price',
      'variation_stock_type',
      'variation_stock_quantity',
      'variation_image_url',
      'variation_nutrition_facts',
      'variation_allergens',
    ];
    const hasVariation = hasAnyValue(row, variationFields);

    if (hasVariation) {
      ['variation_name', 'variation_price'].forEach((field) => {
        if (!(row[field] ?? '').trim()) {
          errors.push({
            row: rowNumber,
            field,
            message: `${field} is required when variation data is provided`,
          });
        }
      });

      if ((row.variation_price ?? '').trim()) {
        const variationPrice = Number(row.variation_price);
        if (!Number.isFinite(variationPrice) || variationPrice <= 0) {
          errors.push({
            row: rowNumber,
            field: 'variation_price',
            message: 'variation_price must be a number greater than 0',
          });
        }
      }

      if ((row.variation_sku ?? '').trim().length > 100) {
        errors.push({
          row: rowNumber,
          field: 'variation_sku',
          message: 'variation_sku can have at most 100 characters',
        });
      }

      const nutritionError = nutritionFactsError(row.variation_nutrition_facts ?? '');
      if (nutritionError) {
        errors.push({
          row: rowNumber,
          field: 'variation_nutrition_facts',
          message: nutritionError,
        });
      }

      const allergenError = allergensError(row.variation_allergens ?? '');
      if (allergenError) {
        errors.push({
          row: rowNumber,
          field: 'variation_allergens',
          message: allergenError,
        });
      }

      const variationStockType = stockTypeOf(
        row.variation_stock_type,
        row.variation_stock_quantity,
      );
      if (!['limited', 'unlimited'].includes(variationStockType)) {
        errors.push({
          row: rowNumber,
          field: 'variation_stock_type',
          message: 'variation_stock_type must be limited or unlimited',
        });
      }

      if (variationStockType === 'limited') {
        if (!(row.variation_stock_quantity ?? '').trim()) {
          errors.push({
            row: rowNumber,
            field: 'variation_stock_quantity',
            message: 'variation_stock_quantity is required for limited variation stock',
          });
        } else if (!isFiniteNumber(row.variation_stock_quantity)) {
          errors.push({
            row: rowNumber,
            field: 'variation_stock_quantity',
            message: 'variation_stock_quantity must be a valid number',
          });
        }
      }

      if (variationStockType === 'unlimited' && (row.variation_stock_quantity ?? '').trim()) {
        errors.push({
          row: rowNumber,
          field: 'variation_stock_quantity',
          message: 'variation_stock_quantity must be empty for unlimited variation stock',
        });
      }

      if ((row.variation_image_url ?? '').trim() && !isValidHttpUrl(row.variation_image_url)) {
        errors.push({
          row: rowNumber,
          field: 'variation_image_url',
          message: 'variation_image_url must be a valid public URL',
        });
      }
    }

    const addonFields = [
      'addon_group_name',
      'addon_group_description',
      'addon_required',
      'addon_selection_type',
      'addon_min_select',
      'addon_max_select',
      'addon_option_title',
      'addon_option_description',
      'addon_option_price',
      'addon_option_stock_type',
      'addon_option_stock_quantity',
      'addon_variation_names',
    ];

    const hasAddonData = hasAnyValue(row, addonFields);

    if (hasAddonData) {
      const requiredAddonFields = [
        'addon_group_name',
        'addon_required',
        'addon_selection_type',
        'addon_option_title',
        'addon_option_price',
        'addon_option_stock_type',
      ];

      requiredAddonFields.forEach((field) => {
        if (!(row[field] ?? '').trim()) {
          errors.push({
            row: rowNumber,
            field,
            message: `${field} is required when add-on data is provided`,
          });
        }
      });

      const addonRequired = normalize(row.addon_required ?? '');
      if (addonRequired && !['yes', 'no'].includes(addonRequired)) {
        errors.push({
          row: rowNumber,
          field: 'addon_required',
          message: 'addon_required must be yes or no',
        });
      }

      const addonSelectionType = normalize(row.addon_selection_type ?? '');
      if (addonSelectionType && !['single', 'multiple'].includes(addonSelectionType)) {
        errors.push({
          row: rowNumber,
          field: 'addon_selection_type',
          message: 'addon_selection_type must be single or multiple',
        });
      }

      const limitsError = selectionLimitsError(row);
      if (limitsError) {
        errors.push({
          row: rowNumber,
          field: 'addon_min_select',
          message: limitsError,
        });
      }

      if ((row.addon_option_price ?? '').trim() && !isFiniteNumber(row.addon_option_price)) {
        errors.push({
          row: rowNumber,
          field: 'addon_option_price',
          message: 'addon_option_price must be a valid number',
        });
      }

      const optionStockType = normalize(row.addon_option_stock_type ?? '');
      if (optionStockType && !['limited', 'unlimited'].includes(optionStockType)) {
        errors.push({
          row: rowNumber,
          field: 'addon_option_stock_type',
          message: 'addon_option_stock_type must be limited or unlimited',
        });
      }

      if (optionStockType === 'limited') {
        if (!(row.addon_option_stock_quantity ?? '').trim()) {
          errors.push({
            row: rowNumber,
            field: 'addon_option_stock_quantity',
            message: 'addon_option_stock_quantity is required for limited add-on stock',
          });
        } else if (!isFiniteNumber(row.addon_option_stock_quantity)) {
          errors.push({
            row: rowNumber,
            field: 'addon_option_stock_quantity',
            message: 'addon_option_stock_quantity must be a valid number',
          });
        }
      }

      if (optionStockType === 'unlimited' && (row.addon_option_stock_quantity ?? '').trim()) {
        errors.push({
          row: rowNumber,
          field: 'addon_option_stock_quantity',
          message: 'addon_option_stock_quantity must be empty for unlimited add-on stock',
        });
      }
    }
  });

  // Variation names of each product, in lower case like the server compares them.
  const variationNamesByProduct = new Map<string, Set<string>>();
  rows.filter(isCompleteVariation).forEach((row) => {
    const key = productKeyOf(row);
    const names = variationNamesByProduct.get(key) ?? new Set<string>();
    names.add(normalize(row.variation_name));
    variationNamesByProduct.set(key, names);
  });
  // A product is either a single product (no variation rows, its own
  // product_price) or a product with variations (one row per variation).
  const keysOfRowsWith = (field: string) =>
    new Set(
      rows.filter((row) => (row[field] ?? '').trim()).map(productKeyOf),
    );
  const productsWithPrice = keysOfRowsWith('product_price');
  const productsWithAddonVariationNames = keysOfRowsWith('addon_variation_names');
  const checkedProducts = new Set<string>();

  rows.forEach((row, index) => {
    const key = productKeyOf(row);
    if (!key || checkedProducts.has(key)) return;
    checkedProducts.add(key);
    const hasVariation = variationNamesByProduct.has(key);
    const hasPrice = productsWithPrice.has(key);
    const product = productLabelOf(row);

    if (!hasVariation && !hasPrice) {
      errors.push({
        row: index + 2,
        field: 'product_price',
        message: messages.productNeedsPriceOrVariation(product),
      });
    } else if (hasVariation && hasPrice) {
      errors.push({
        row: index + 2,
        field: 'product_price',
        message: messages.productWithVariationsHasPrice(product),
      });
    } else if (!hasVariation && productsWithAddonVariationNames.has(key)) {
      errors.push({
        row: index + 2,
        field: 'addon_variation_names',
        message: messages.singleProductHasAddonVariationNames(product),
      });
    }
  });

  // An add-on group can only be limited to variations of its own product.
  rows.forEach((row, index) => {
    const variationNames = variationNamesByProduct.get(productKeyOf(row));
    if (!variationNames) return;
    parseVariationNames(row.addon_variation_names)
      .filter((name) => !variationNames.has(normalize(name)))
      .forEach((name) => {
        errors.push({
          row: index + 2,
          field: 'addon_variation_names',
          message: messages.unknownAddonVariation(name, productLabelOf(row)),
        });
      });
  });

  // A category has one schedule, so every row that fills it must agree.
  const categorySchedules = new Map<string, string>();
  const conflictingCategories = new Set<string>();
  rows.forEach((row, index) => {
    const category = (row.category ?? '').trim();
    const { fromTime, untilTime } = categoryScheduleOf(row);
    if (!category || !fromTime || !untilTime) return;
    const schedule = `${fromTime}-${untilTime}`;
    const first = categorySchedules.get(category);
    if (first === undefined) {
      categorySchedules.set(category, schedule);
    } else if (first !== schedule && !conflictingCategories.has(category)) {
      conflictingCategories.add(category);
      errors.push({
        row: index + 2,
        field: 'category_available_from',
        message: `Category "${category}" has different available times on different rows; use the same times on every row, or leave them empty`,
      });
    }
  });

  // A group's settings come from its first row, like the server reads them.
  const addonGroups = new Map<string, { row: number; source: CsvRow; options: Set<string> }>();
  rows.forEach((row, index) => {
    const groupName = (row.addon_group_name ?? '').trim();
    const optionTitle = (row.addon_option_title ?? '').trim();
    if (!groupName || !optionTitle) return;
    const key = `${productKeyOf(row)}\u0000${groupName}`;
    const group = addonGroups.get(key)
      ?? { row: index + 2, source: row, options: new Set<string>() };
    group.options.add(optionTitle);
    addonGroups.set(key, group);
  });
  addonGroups.forEach(({ row, source, options }) => {
    if (normalize(source.addon_selection_type ?? '') !== 'multiple') return;
    const highest = Math.max(
      Number(source.addon_min_select) || 0,
      Number(source.addon_max_select) || 0,
    );
    if (highest > options.size) {
      errors.push({
        row,
        field: 'addon_max_select',
        message: `${source.addon_group_name} has ${options.size} option(s), so minimum and maximum cannot be higher than ${options.size}`,
      });
    }
  });

  return { headers, rows, errors };
};

interface BulkProductUploadDialogProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  storeId?: string;
  onUploadQueued: (upload: BulkUploadProductsResponse, fileName: string) => void;
}

export function BulkProductUploadDialog({
  open,
  onOpenChange,
  storeId,
  onUploadQueued,
}: BulkProductUploadDialogProps) {
  const t = useTranslations('products.bulkUpload');
  const tErrors = useTranslations('products.bulkUpload.errors');
  const [file, setFile] = React.useState<File | null>(null);
  const [preview, setPreview] = React.useState<CsvPreviewState | null>(null);

  const { mutate: uploadBulkProducts, isPending } = useBulkUploadProducts({
    onSuccess: (response) => {
      onUploadQueued(response, file?.name || t('noFileSelected'));
      toast.success(response.message || t('success.uploadQueued'));
      resetDialog();
      onOpenChange(false);
    },
    onError: (error) => {
      toast.error(returnErrorMessage(error as ApiErrorResponse) || t('errors.uploadFailed'));
    },
  });
  const isBusy = isPending;

  const hasErrors = (preview?.errors.length ?? 0) > 0;
  const validRowCount = React.useMemo(() => {
    if (!preview) return 0;
    if (preview.errors.some((error) => error.row === 1)) return 0;

    const invalidRows = new Set(
      preview.errors
        .filter((error) => error.row > 1)
        .map((error) => error.row),
    );

    return Math.max(preview.rows.length - invalidRows.size, 0);
  }, [preview]);

  const resetDialog = () => {
    setFile(null);
    setPreview(null);
  };

  const handleClose = () => {
    if (isBusy) return;
    onOpenChange(false);
    resetDialog();
  };

  const handleFileChange = async (selectedFile: File | null) => {
    if (isBusy) return;
    setFile(selectedFile);
    setPreview(null);

    if (!selectedFile) return;

    if (!selectedFile.name.toLowerCase().endsWith('.csv')) {
      toast.error(t('errors.invalidFileType'));
      return;
    }

    if (selectedFile.size > MAX_UPLOAD_SIZE_BYTES) {
      toast.error(t('errors.fileTooLarge'));
      return;
    }

    const content = decodeCsvBuffer(await selectedFile.arrayBuffer());
    const parsed = buildCsvPreview(content, {
      unknownAddonVariation: (variation, product) =>
        t('errors.unknownAddonVariation', { variation, product }),
      productNeedsPriceOrVariation: (product) =>
        tErrors('productNeedsPriceOrVariation', { product }),
      productWithVariationsHasPrice: (product) =>
        tErrors('productWithVariationsHasPrice', { product }),
      singleProductHasAddonVariationNames: (product) =>
        tErrors('singleProductHasAddonVariationNames', { product }),
      productPriceInvalid: () => tErrors('productPriceInvalid'),
    });
    setPreview(parsed);
  };

  const handleUpload = () => {
    if (!storeId) {
      toast.error(t('errors.storeIdRequired'));
      return;
    }

    if (!file) {
      toast.error(t('errors.fileRequired'));
      return;
    }

    if (!preview) {
      toast.error(t('errors.previewRequired'));
      return;
    }

    if (hasErrors) {
      toast.error(t('errors.fixErrorsBeforeUpload'));
      return;
    }

    uploadBulkProducts({
      file,
      store_id: storeId,
      importMode: 'create',
      autoCreateMasterData: true,
    });
  };

  const previewRows = preview?.rows.slice(0, 10) ?? [];

  return (
    <AppDialog
      open={open}
      onClose={handleClose}
      title={t('title')}
      size="6xl"
      showCloseButton={!isBusy}
      showDefaultFooter={false}
      footer={(
        <div className="flex w-full justify-end gap-3">
          <AppButton
            type="button"
            variant="secondary"
            onClick={handleClose}
            disabled={isBusy}
          >
            {t('buttons.cancel')}
          </AppButton>
          <AppButton
            type="button"
            leftIcon={<Upload size={16} />}
            onClick={handleUpload}
            isLoading={isBusy}
            disabled={!file || !preview || hasErrors || isBusy}
          >
            {t('buttons.upload')}
          </AppButton>
        </div>
      )}
    >
      <div className="space-y-5" aria-busy={isBusy}>
        <div className="rounded-xl border bg-white p-4">
          <div className="flex flex-wrap items-start justify-between gap-3">
            <div>
              <p className="text-sm text-muted-foreground">{t('description')}</p>
              <ul className="mt-2 list-disc space-y-1 ps-4 text-xs text-muted-foreground">
                <li>{t('shapeSingle')}</li>
                <li>{t('shapeVariations')}</li>
                <li>{t('shapeAddons')}</li>
                <li>{t('shapeCategorySchedule')}</li>
              </ul>
              <p className="mt-2 text-xs text-muted-foreground">{t('optionalColumnsHint')}</p>
            </div>
            <a
              className="inline-flex h-10 items-center rounded-md border border-ink px-4 text-sm font-medium text-ink transition-colors hover:bg-primary hover:text-primary-foreground focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ink focus-visible:ring-offset-2"
              download="pohanch-bulk-products-sample.csv"
              href="/templates/pohanch-bulk-products-sample.csv"
            >
              <Download size={16} className="mr-2" aria-hidden="true" />
              {t('buttons.downloadSample')}
            </a>
          </div>
          <div className="mt-4 flex flex-wrap items-center gap-3">
            <label
              htmlFor="bulk-upload-csv"
              className={`inline-flex h-10 items-center rounded-md border px-4 text-sm font-medium ${
                isBusy
                  ? 'cursor-not-allowed opacity-60'
                  : 'cursor-pointer hover:bg-accent'
              }`}
            >
              <FileText size={16} className="mr-2" />
              {t('buttons.chooseFile')}
            </label>
            <input
              id="bulk-upload-csv"
              type="file"
              accept=".csv,text/csv"
              className="hidden"
              disabled={isBusy}
              onChange={(event) => {
                const selectedFile = event.target.files?.[0] ?? null;
                handleFileChange(selectedFile);
              }}
            />
            <span className="text-sm text-muted-foreground">
              {file?.name || t('noFileSelected')}
            </span>
          </div>
        </div>

        {isBusy ? (
          <div
            className="rounded-xl border border-ink/30 bg-primary/5 p-4"
            role="status"
            aria-live="polite"
          >
            <div className="flex items-start gap-3">
              <Loader2 className="mt-0.5 size-5 shrink-0 animate-spin text-ink" aria-hidden="true" />
              <div>
                <p className="text-sm font-semibold text-foreground">
                  {t('progress.uploading')}
                </p>
                <p className="mt-1 text-sm text-muted-foreground">
                  {t('progress.submitting')}
                </p>
              </div>
            </div>
            <div className="mt-3 h-1.5 overflow-hidden rounded-full bg-primary/15">
              <div className="h-full w-1/2 animate-pulse rounded-full bg-primary" />
            </div>
          </div>
        ) : null}

        {preview && (
          <div className="space-y-4">
            <div className="grid grid-cols-1 gap-3 md:grid-cols-3">
              <div className="rounded-lg border bg-white p-3">
                <p className="text-xs text-muted-foreground">{t('summary.totalRows')}</p>
                <p className="text-lg font-semibold">{preview.rows.length}</p>
              </div>
              <div className="rounded-lg border bg-white p-3">
                <p className="text-xs text-muted-foreground">{t('summary.validRows')}</p>
                <p className="text-lg font-semibold">{validRowCount}</p>
              </div>
              <div className="rounded-lg border bg-white p-3">
                <p className="text-xs text-muted-foreground">{t('summary.errors')}</p>
                <p className="text-lg font-semibold text-destructive">{preview.errors.length}</p>
              </div>
            </div>

            {preview.errors.length > 0 && (
              <div className="rounded-xl border border-destructive/40 bg-destructive/5 p-4">
                <div className="mb-2 flex items-center gap-2 text-destructive">
                  <AlertTriangle size={16} />
                  <p className="text-sm font-semibold">{t('errors.validationTitle')}</p>
                </div>
                <div className="max-h-44 overflow-auto rounded-md border bg-white">
                  <table className="min-w-full text-sm">
                      <thead className="bg-accent/60 text-left">
                        <tr>
                          <th className="whitespace-nowrap px-3 py-2">{t('errors.columns.row')}</th>
                          <th className="whitespace-nowrap px-3 py-2">{t('errors.columns.field')}</th>
                          <th className="whitespace-nowrap px-3 py-2">{t('errors.columns.message')}</th>
                        </tr>
                      </thead>
                      <tbody>
                        {preview.errors.slice(0, 100).map((errorItem, index) => (
                          <tr key={`${errorItem.row}-${errorItem.field}-${index}`} className="border-t">
                            <td className="whitespace-nowrap px-3 py-2">{errorItem.row}</td>
                            <td className="whitespace-nowrap px-3 py-2 font-medium">{errorItem.field}</td>
                            <td className="whitespace-nowrap px-3 py-2">{errorItem.message}</td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                </div>
              </div>
            )}

            <div className="rounded-xl border bg-white p-4">
              <p className="mb-2 text-sm font-semibold">{t('preview.title')}</p>
              <p className="mb-3 text-xs text-muted-foreground">{t('preview.subtitle')}</p>
              <div className="max-h-64 overflow-auto rounded-md border bg-white">
                  <table className="min-w-max text-sm">
                    <thead className="bg-accent/60 text-left">
                      <tr>
                        {CSV_HEADERS.map((header) => (
                          <th key={header} className="whitespace-nowrap px-3 py-2">
                            {header}
                          </th>
                        ))}
                      </tr>
                    </thead>
                    <tbody>
                      {previewRows.map((row, rowIndex) => (
                        <tr key={`preview-row-${rowIndex}`} className="border-t">
                          {CSV_HEADERS.map((header) => (
                            <td
                              key={`${rowIndex}-${header}`}
                              className="whitespace-nowrap px-3 py-2 align-top"
                            >
                              {row[header] || '-'}
                            </td>
                          ))}
                        </tr>
                      ))}
                    </tbody>
                    </table>
              </div>
            </div>
          </div>
        )}
      </div>
    </AppDialog>
  );
}
